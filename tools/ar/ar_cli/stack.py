"""The Compose stack (compose.yaml): env file, lifecycle, health, backup/restore, logs."""

import json
import os
import re
import secrets
import time
import urllib.error
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .paths import PROJECT, Paths, parse_env_file
from .runner import Runner
from .state import State, write_private

DB_USER = "autoresilience"
DB_NAME = "autoresilience"
PG_DUMP_MAGIC = b"PGDMP"  # pg_dump custom-format header
SERVICES = ("postgres", "migrate", "api", "web")


def compose(paths: Paths, *args: str) -> list[str]:
    return [
        "docker",
        "compose",
        "-p",
        PROJECT,
        "-f",
        str(paths.compose_file),
        "--project-directory",
        str(paths.root),
        "--env-file",
        str(paths.stack_env),
        *args,
    ]


def write_stack_env(paths: Paths, state: State) -> None:
    """The env file compose.yaml interpolates. Keeps an existing database password."""
    existing = parse_env_file(paths.stack_env.read_text()) if paths.stack_env.exists() else {}
    values = {
        # Generated once; the data volume is initialised with it, so it is never rotated here.
        "AUTORESILIENCE_DB_PASSWORD": existing.get("AUTORESILIENCE_DB_PASSWORD") or secrets.token_urlsafe(24),
        "AUTORESILIENCE_KUBECONFIG": str(paths.kubeconfig),
        "AUTORESILIENCE_WEB_PORT": str(state.web_port),
        "AUTORESILIENCE_API_PORT": str(state.api_port),
    }
    if hasattr(os, "getuid"):  # run the engine as the host user so the 0600 kubeconfig is readable
        values["AUTORESILIENCE_UID"] = str(os.getuid())
        values["AUTORESILIENCE_GID"] = str(os.getgid())
    header = "# Generated by tools/ar; contains the local database password. Do not commit.\n"
    write_private(paths.stack_env, header + "".join(f"{k}={v}\n" for k, v in values.items()))


def build(runner: Runner, paths: Paths) -> None:
    runner.stream(compose(paths, "build"))


def up(runner: Runner, paths: Paths) -> None:
    # --wait: returns once postgres/api/web are healthy and migrate has exited 0.
    runner.stream(compose(paths, "up", "-d", "--wait", "--wait-timeout", "300"), timeout=600)


def stop(runner: Runner, paths: Paths) -> None:
    runner.stream(compose(paths, "stop"))


def down(runner: Runner, paths: Paths) -> None:
    """Remove containers, networks and locally built images. Never volumes (no -v)."""
    runner.stream(compose(paths, "down", "--rmi", "local", "--remove-orphans"))


@dataclass(frozen=True)
class ServiceState:
    service: str
    state: str  # running | exited | created | missing ...
    health: str  # healthy | unhealthy | starting | "" (no healthcheck)
    exit_code: int | None


def parse_ps(output: str) -> dict[str, ServiceState]:
    """`docker compose ps --format json`: NDJSON (Compose >= 2.21) or a JSON array."""
    text = output.strip()
    if not text:
        return {}
    rows: list[dict[str, Any]] = (
        json.loads(text) if text.startswith("[") else [json.loads(line) for line in text.splitlines() if line.strip()]
    )
    return {
        row["Service"]: ServiceState(
            service=row["Service"],
            state=str(row.get("State", "")),
            health=str(row.get("Health", "")),
            exit_code=row.get("ExitCode"),
        )
        for row in rows
    }


def services(runner: Runner, paths: Paths) -> dict[str, ServiceState]:
    if not paths.stack_env.exists():
        return {}
    result = runner.run(compose(paths, "ps", "-a", "--format", "json"), check=False)
    return parse_ps(result.stdout) if result.ok else {}


def get_json(url: str, timeout: float = 5) -> tuple[int | None, Any]:
    """(HTTP status, parsed body); (None, reason) when nothing answered."""
    try:
        with urllib.request.urlopen(url, timeout=timeout) as response:
            return response.status, json.loads(response.read() or b"null")
    except urllib.error.HTTPError as exc:
        try:
            return exc.code, json.loads(exc.read() or b"null")
        except ValueError:
            return exc.code, None
    except (OSError, ValueError) as exc:
        return None, str(getattr(exc, "reason", exc))


def wait_ready(api_url: str, timeout: float = 180, sleep: Callable[[float], None] = time.sleep) -> Any:
    deadline = time.monotonic() + timeout
    while True:
        status, body = get_json(f"{api_url}/ready")
        if status == 200:
            return body
        if time.monotonic() > deadline:
            raise TimeoutError(f"{api_url}/ready did not become ready: {status} {body}")
        sleep(3)


# --- backup / restore ---------------------------------------------------------------


def backup(runner: Runner, paths: Paths, now: Callable[[], datetime] = lambda: datetime.now(UTC)) -> Path:
    """pg_dump (custom format) of the stack database into ~/.autoresilience/backups."""
    result = runner.run(
        compose(paths, "exec", "-T", "postgres", "pg_dump", "-U", DB_USER, "-d", DB_NAME, "-Fc"), timeout=600
    )
    if not result.stdout_bytes.startswith(PG_DUMP_MAGIC):
        raise ValueError("pg_dump did not return a custom-format dump; nothing was written")
    stamp = now().strftime("%Y%m%dT%H%M%SZ")
    paths.backups.mkdir(parents=True, exist_ok=True, mode=0o700)
    target = paths.backups / f"autoresilience-{stamp}.dump"
    suffix = 1
    while target.exists():  # never overwrite an earlier backup
        target = paths.backups / f"autoresilience-{stamp}-{suffix}.dump"
        suffix += 1
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as handle:
        handle.write(result.stdout_bytes)
    return target


def read_dump(path: Path) -> bytes:
    data = path.read_bytes()
    if not data.startswith(PG_DUMP_MAGIC):
        raise ValueError(f"{path} is not a pg_dump custom-format file (created by `ar backup`)")
    return data


def restore(runner: Runner, paths: Paths, dump: bytes) -> None:
    """Replace the database contents with a dump. The engine is stopped meanwhile."""
    runner.stream(compose(paths, "stop", "api", "web"))
    runner.run(
        compose(
            paths,
            "exec",
            "-T",
            "postgres",
            "pg_restore",
            "-U",
            DB_USER,
            "-d",
            DB_NAME,
            "--clean",
            "--if-exists",
            "--no-owner",
            "--single-transaction",
        ),
        input=dump,
        timeout=600,
    )
    up(runner, paths)  # migrate runs first, so an older dump is brought to the current head


# --- diagnostics ----------------------------------------------------------------------

_SECRETS = [
    (re.compile(r"(://[^:/@\s]+:)[^@\s]+@"), r"\1***@"),
    (re.compile(r"(?i)(password|token|secret)(\"?\s*[:=]\s*\"?)[^\s\",]+"), r"\1\2***"),
    (re.compile(r"eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+"), "***jwt***"),
]


def redact(text: str) -> str:
    for pattern, replacement in _SECRETS:
        text = pattern.sub(replacement, text)
    return text


def logs(runner: Runner, paths: Paths, tail: int) -> str:
    result = runner.run(compose(paths, "logs", "--no-color", "--tail", str(tail)), check=False)
    return redact(result.stdout + result.stderr)
