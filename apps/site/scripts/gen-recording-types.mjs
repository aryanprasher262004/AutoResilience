// Generates src/lib/recordings/schema.ts from the committed recording JSON Schemas
// (packages/contracts/recorded-{experiment,validation}.schema.json, themselves generated
// from Pydantic). openapi-typescript reads OpenAPI, so each schema's $defs are wrapped as
// components. Run after changing app/schemas/recording.py: scripts/gen-api-contracts.sh.
import { readFileSync, writeFileSync } from "node:fs";

import openapiTS, { astToString } from "openapi-typescript";

const contracts = new URL("../../../packages/contracts/", import.meta.url);
const target = new URL("../src/lib/recordings/schema.ts", import.meta.url);

const schemas = {};
for (const [file, name] of [
  ["recorded-experiment.schema.json", "RecordedExperiment"],
  ["recorded-validation.schema.json", "RecordedValidation"],
]) {
  const schema = JSON.parse(readFileSync(new URL(file, contracts), "utf8"));
  const { $defs = {}, $id, ...root } = schema;
  void $id;
  for (const [key, value] of Object.entries($defs)) {
    if (schemas[key] && JSON.stringify(schemas[key]) !== JSON.stringify(value)) {
      throw new Error(`conflicting definitions for ${key}`);
    }
    schemas[key] = value;
  }
  schemas[name] = root;
}

const document = JSON.parse(
  JSON.stringify({
    openapi: "3.1.0",
    info: { title: "AutoResilience recordings", version: "1" },
    paths: {},
    components: { schemas },
  }).replaceAll("#/$defs/", "#/components/schemas/"),
);

const ast = await openapiTS(document);
writeFileSync(
  target,
  "// Generated by apps/site/scripts/gen-recording-types.mjs from packages/contracts/recorded-*.schema.json. Do not edit.\n" +
    astToString(ast),
);
console.log(`wrote ${target.pathname}`);
